const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const BASE_URL=process.env.BASE_URL||'http://127.0.0.1:4173/ranking';
const snapshot=JSON.parse(fs.readFileSync(path.join(ROOT,'assets/data/ranking.json')));
const artifacts=path.join(ROOT,BASE_URL.startsWith('https://')?'docs/previews-production':'docs/previews');fs.mkdirSync(artifacts,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1080},timezoneId:'Asia/Seoul',colorScheme:'light'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const response=await page.goto(BASE_URL);
 assert.equal(response.status(),200);
 assert.equal(await page.title(),'2026 SOOP 올해의 스트리머 예상 랭킹');
 assert.match(await page.locator('meta[name=description]').getAttribute('content'),/비공식 예상 랭킹/);
 assert.match(await page.locator('meta[property="og:title"]').getAttribute('content'),/2026 SOOP/);
 await page.waitForSelector('.ranked-row');
 assert.equal(await page.locator('.ranked-row').count(),100);
 assert.equal(await page.locator('.cutline').count(),1);
 assert.match(await page.locator('#data-status').innerText(),/98명/);
 await page.screenshot({path:path.join(artifacts,'desktop.png')});
 for(const model of ['rank','percentile','ratio','minmax']){
   await page.locator(`[data-model=${model}]`).click();
   await page.locator('[data-filter=top]').click();
   assert.equal(await page.locator('.ranked-row').count(),70);
   await page.locator('[data-filter=all]').click();
 }
 await page.locator('[data-model=rank]').click();
 await page.locator('[data-filter=boundary]').click();
 assert.equal(await page.locator('.ranked-row').count(),21);
 await page.screenshot({path:path.join(artifacts,'boundary.png')});
 await page.locator('[data-filter=all]').click();
 await page.locator('#search').fill('봉준');
 assert.equal(await page.locator('.ranked-row').count(),1);
 assert.match(await page.locator('#search-summary').innerText(),/70위 기준/);
 const trigger=page.locator('.streamer-button');await trigger.focus();await page.keyboard.press('Enter');
 assert.equal(await page.locator('#detail-dialog').evaluate(d=>d.open),true);
 assert.match(await page.locator('#detail-content').innerText(),new RegExp(snapshot.streamers.find(r=>r.soopId==='khm11903').cumulativeUsers.toLocaleString('ko-KR')));
 await page.screenshot({path:path.join(artifacts,'detail.png')});
 await page.keyboard.press('Escape');assert.equal(await trigger.evaluate(e=>e===document.activeElement),true);
 await page.locator('#search').fill('danchu17');await page.locator('.streamer-button').click();
 assert.match(await page.locator('#detail-content').innerText(),/산정 대기/);await page.keyboard.press('Escape');
 await page.locator('#search').fill('no_such_streamer');assert.equal(await page.locator('#empty').isVisible(),true);
 await page.locator('#reset-search').click();
 await page.locator('#method-open').click();assert.match(await page.locator('#exclusion-list').innerText(),/LCK_KR/);await page.keyboard.press('Escape');
 for(const width of [1024,850,768,390,320]){
  await page.setViewportSize({width,height:900});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,`Horizontal overflow at ${width}px`);
  if(width===390)await page.screenshot({path:path.join(artifacts,'mobile.png')});
 }
 await page.locator('#theme').click();assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.setViewportSize({width:1440,height:1080});await page.screenshot({path:path.join(artifacts,'dark.png')});
 assert.deepEqual(errors,[],`JS/CSP errors: ${errors.join(';')}`);
 const statePage=await browser.newPage();
 await statePage.route('**/assets/data/ranking.json',route=>route.fulfill({json:{...snapshot,status:'stale',message:'테스트 갱신 실패'}}));
 await statePage.goto(BASE_URL);await statePage.waitForSelector('.ranked-row');
 assert.match(await statePage.locator('#data-status').innerText(),/마지막 확인값/);
 await statePage.unroute('**/assets/data/ranking.json');
 await statePage.route('**/assets/data/ranking.json',route=>route.fulfill({json:{status:'unavailable',streamers:[],exclusions:[],message:'테스트 데이터 없음'}}));
 await statePage.reload();await statePage.waitForSelector('#fetch-error');assert.equal(await statePage.locator('#table-wrap').isVisible(),false);
 await statePage.unroute('**/assets/data/ranking.json');await statePage.locator('#retry').click();await statePage.waitForSelector('.ranked-row');
 assert.equal(await statePage.locator('.ranked-row').count(),100);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,timezoneId:'Asia/Seoul'});
 await mobile.goto(BASE_URL);await mobile.waitForSelector('.ranked-row');
 await mobile.locator('[data-model=ratio]').tap();
 assert.equal(await mobile.locator('[data-model=ratio]').getAttribute('aria-pressed'),'true');
 await mobile.locator('#search').fill('singgyul');assert.equal(await mobile.locator('.ranked-row').count(),1);
 await mobile.locator('.streamer-button').tap();assert.match(await mobile.locator('#detail-content').innerText(),/띵귤_/);
 await mobile.locator('#detail-dialog [data-close]').tap();
 await mobile.locator('#search').fill('');await mobile.locator('[data-filter=boundary]').tap();
 await mobile.locator('.cutline').scrollIntoViewIfNeeded();
 assert.equal(await mobile.locator('.cutline').isVisible(),true);
 await mobile.screenshot({path:path.join(artifacts,'mobile-boundary.png')});
 await browser.close();console.log('Browser PASS: 4 models, boundary, search, keyboard/dialog, hidden data, methodology, light/dark, 5 widths, stale/unavailable/retry, CSP.');
})().catch(e=>{console.error(e);process.exit(1)});
